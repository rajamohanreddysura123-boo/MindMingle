/**
 * The catalog to fall back on when `appConfig/plans` is missing or empty, and the one an admin
 * restores with "Restore defaults". [dialCodes] maps ISO country code to dial code and comes from
 * [CountryCodeRepository]; a country with no dial code still gets a row, it just cannot be
 * resolved from a phone number.
 */
fun defaultPlanCatalog(dialCodes: Map<String, String> = emptyMap()): PlanCatalog = PlanCatalog(
    enabled = true,
    defaultCountry = DEFAULT_PLAN_COUNTRY,
    countries = COUNTRY_CURRENCIES.mapValues { (code, spec) ->
        CountryPricing(
            countryCode = code,
            currency = spec.currency,
            symbol = spec.symbol,
            decimals = spec.decimals,
            dialCode = dialCodes[code].orEmpty(),
            monthly = spec.monthly,
            annual = spec.annual
        )
    },
    resolvedCountry = DEFAULT_PLAN_COUNTRY
)

/**
 * Resolves the market a phone number belongs to, longest dial code first so +971 beats +97 and
 * +1 never shadows a longer North American code. Returns null when nothing matches.
 */
fun countryFromPhone(phoneNumber: String, dialCodes: Map<String, String>): String? {
    val digits = phoneNumber.filter { it.isDigit() || it == '+' }
    if (!digits.startsWith("+")) return null

    return dialCodes.entries
        .filter { (_, dial) -> dial.length > 1 && digits.startsWith(dial.filter { c -> c.isDigit() || c == '+' }) }
        .maxByOrNull { (_, dial) -> dial.length }
        ?.key
}
