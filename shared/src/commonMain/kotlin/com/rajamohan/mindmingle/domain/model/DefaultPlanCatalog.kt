package com.rajamohan.mindmingle.domain.model

/**
 * The seed for `appConfig/plans` — the Firestore doc that MindMingle+ pricing is actually read
 * from. Prices are NOT set from a Cloud Function: any signed-in client reads the doc directly
 * and an admin edits it from the Plan Pricing screen (see firestore.rules, appConfig).
 *
 * Every country in `files/CountryCodes.json` has a row here so the admin screen can list all of
 * them, but only the markets we have actually priced carry non-zero amounts. A zero row means
 * "not priced yet" — checkout falls back to [PlanCatalog.defaultCountry] until an admin fills it
 * in. Dial codes are not duplicated here; they come from [CountryCodeRepository].
 *
 * Amounts are in the currency's smallest unit, which is what Razorpay charges in:
 *   decimals 2 -> paise/cents  (INR 99.00 = 9900)
 *   decimals 0 -> whole units  (JPY 399 = 399)
 *   decimals 3 -> fils         (KWD 0.999 = 999)
 */
data class CurrencySpec(
    val currency: String,
    val symbol: String,
    val decimals: Int,
    val monthly: Long,
    val annual: Long
)

